// Rasterises every Lucide icon into 1024x1024 sprite sheets that RiftUI downloads and
// loads through getcustomasset. Writes public/assets/lucide/sheet-N.png and the
// ordered name list the library uses to locate a cell.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Resvg } from '@resvg/resvg-js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconDir = join(root, 'node_modules/lucide-static/icons')
const outDir = join(root, 'public/assets/lucide')
mkdirSync(outDir, { recursive: true })

export const CELL = 48
export const INSET = 2
export const SHEET = 1024
const perRow = Math.floor(SHEET / CELL)
const perSheet = perRow * perRow

const names = readdirSync(iconDir)
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.slice(0, -4))
  .sort()

const inner = (name) => {
  const svg = readFileSync(join(iconDir, name + '.svg'), 'utf8')
  return svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
}

const sheets = Math.ceil(names.length / perSheet)
for (let s = 0; s < sheets; s++) {
  const parts = []
  for (let i = s * perSheet; i < Math.min(names.length, (s + 1) * perSheet); i++) {
    const cell = i - s * perSheet
    const x = (cell % perRow) * CELL + INSET
    const y = Math.floor(cell / perRow) * CELL + INSET
    const size = CELL - INSET * 2
    parts.push(
      `<svg x="${x}" y="${y}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="#ffffff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner(names[i])}</svg>`,
    )
  }
  const doc = `<svg xmlns="http://www.w3.org/2000/svg" width="${SHEET}" height="${SHEET}" viewBox="0 0 ${SHEET} ${SHEET}">${parts.join('')}</svg>`
  const png = new Resvg(doc, { fitTo: { mode: 'original' }, background: 'rgba(0,0,0,0)' }).render().asPng()
  writeFileSync(join(outDir, `sheet-${s}.png`), png)
}

const lucideVersion = JSON.parse(readFileSync(join(root, 'node_modules/lucide-static/package.json'), 'utf8')).version
writeFileSync(
  join(root, 'lib/generated/icons.luau'),
  `-- Generated by scripts/build-icons.mjs from lucide-static ${lucideVersion}. Do not edit.\n` +
    `return {\n\tVersion = "${lucideVersion}",\n\tCell = ${CELL},\n\tInset = ${INSET},\n\tPerRow = ${perRow},\n\tPerSheet = ${perSheet},\n\tSheets = ${sheets},\n\tNames = "${names.join(',')}",\n}\n`,
)
writeFileSync(
  join(outDir, 'SOURCE.txt'),
  `Lucide icons ${lucideVersion} (ISC license, https://lucide.dev), rasterised by scripts/build-icons.mjs:\n` +
    `white 2px strokes, ${CELL}px cells with ${INSET}px inset, ${perSheet} icons per ${SHEET}px sheet, ${names.length} icons in ${sheets} sheets.\n`,
)
// Soft drop shadow, used as a 9-slice behind the dock, panel, popups and pins:
// 80px image, a 40px rounded square centred, so SliceCenter (39,39,41,41) leaves 39px corners
// and a 20px spread lines the square up with the object's edge.
const shadow = `<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"><defs><filter id="b" x="-60%" y="-60%" width="220%" height="220%"><feGaussianBlur stdDeviation="7"/></filter></defs><rect x="20" y="20" width="40" height="40" rx="12" fill="#000" fill-opacity="0.95" filter="url(#b)"/></svg>`
writeFileSync(join(root, 'public/assets/shadow.png'), new Resvg(shadow, { background: 'rgba(0,0,0,0)' }).render().asPng())
